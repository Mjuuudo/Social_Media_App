import uuid
from datetime import datetime
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.user import UserModel, RefreshTokenModel


async def get_by_email(session: AsyncSession, email: str) -> UserModel | None:
    """
    Find a user by email address.

    Args:
        session: The database session.
        email: The email to look up (stored lowercase at registration).

    Returns:
        UserModel | None: The matching user, or None if no user has this email.
    """
    query = select(UserModel).where(UserModel.email == email)
    result = await session.execute(query)
    return result.scalar_one_or_none()


async def get_by_username(session: AsyncSession, username: str) -> UserModel | None:
    """
    Find a user by username.

    Args:
        session: The database session.
        username: The username to look up (stored lowercase at registration).

    Returns:
        UserModel | None: The matching user, or None if the username is not taken.
    """
    query = select(UserModel).where(UserModel.username == username)
    result = await session.execute(query)
    return result.scalar_one_or_none()


async def get_by_id(session: AsyncSession, id: uuid.UUID) -> UserModel:
    """
    Find a user by primary key.

    Args:
        session: The database session.
        id: The user's UUID (for example, taken from a decoded JWT).

    Returns:
        UserModel | None: The matching user, or None if no user has this id.
    """
    query = select(UserModel).where(UserModel.id == id)
    result = await session.execute(query)
    return result.scalar_one_or_none()


async def get_all(session: AsyncSession):
    """
    Return every user in the database.

    Args:
        session: The database session.

    Returns:
        Sequence[UserModel]: All users (not paginated).
    """
    query = select(UserModel)
    result = await session.execute(query)
    return result.scalars().all()


async def save_user(session: AsyncSession, user: UserModel) -> UserModel:
    """
    Insert a new user into the database and commit.

    Args:
        session: The database session.
        user: The `UserModel` instance to persist.

    Returns:
        UserModel: The same user, now saved (its `id` and timestamps are
        generated by the database).
    """
    session.add(user)
    await session.commit()
    return user

async def save_refresh_token( 
            session: AsyncSession,
            user_id: uuid.UUID,
            token_hash: str, 
            expires_at: datetime ) -> RefreshTokenModel :
        """
        Store a new (hashed) refresh token for a user and commit.

        Args:
            session: The database session.
            user_id: The id of the user who owns the token.
            token_hash: The SHA-256 hash of the raw refresh token
                (never the raw token itself).
            expires_at: When the token stops being valid (UTC).

        Returns:
            RefreshTokenModel: The saved refresh-token row.
        """

        refresh_token_model = RefreshTokenModel(
            user_id = user_id,
            token_hash = token_hash,
            expires_at = expires_at,
            
        )

        session.add ( refresh_token_model )
        await session.commit( )

        return refresh_token_model

async def get_refresh_token ( session: AsyncSession, hashed_token: str ) -> RefreshTokenModel :
    """
    Find a refresh-token row by its hash.

    Args:
        session: The database session.
        hashed_token: The SHA-256 hash of the raw refresh token
            (use `hash_refresh_token` first, do not pass the raw token).

    Returns:
        RefreshTokenModel | None: The matching row, or None if not found.
    """
    token_object = select(RefreshTokenModel).where(RefreshTokenModel.token_hash == hashed_token)
    result = await session.execute(token_object)
    return result.scalar_one_or_none()
